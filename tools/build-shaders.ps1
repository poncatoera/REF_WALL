# Compiles shaders/*.slang into shaders/generated/*.glsl (GLSL ES 3.00).
#   slangc  -> SPIR-V          (https://github.com/shader-slang/slang/releases)
#   naga    -> GLSL ES 3.00    (cargo install naga-cli)
# Usage: pwsh tools/build-shaders.ps1   (slangc and naga must be on PATH)
#
# Notes from the first Windows run:
# - slangc names SPIR-V entry points "main" unless -fvk-use-entrypoint-name.
# - Vertex shaders use SV_VulkanVertexID: SV_VertexID compiles to
#   VertexIndex - BaseVertex, which naga can't translate.
# - naga picks the backend from the output extension (.vert / .frag), and
#   exits 0 even when it writes nothing, so check the file exists.
# - naga names each stage's copy of a resource differently
#   (View_std140_block_0Vertex / ...Fragment, _group_0_binding_0_vs / _fs).
#   GL needs one name per uniform block across stages, or linking fails
#   ("members of uniform block ... are not the same between shader stages"),
#   so the stage suffixes are stripped.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root "shaders/generated"
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) "wall-shaders"
New-Item -ItemType Directory -Force -Path $out, $tmp | Out-Null

# name, entry point, slang stage, output suffix
$entries = @(
    @("sdf_box", "vs_main", "vertex",   "vert"),
    @("sdf_box", "fs_main", "fragment", "frag"),
    @("glyph",   "vs_main", "vertex",   "vert"),
    @("glyph",   "fs_main", "fragment", "frag"),
    @("image",   "vs_main", "vertex",   "vert"),
    @("image",   "fs_main", "fragment", "frag"),
    @("curve",   "vs_main", "vertex",   "vert"),
    @("curve",   "fs_main", "fragment", "frag")
)

foreach ($e in $entries) {
    $name, $entry, $stage, $suffix = $e
    $src = Join-Path $root "shaders/$name.slang"
    $spv = Join-Path $tmp "$name.$suffix.spv"
    $staged = Join-Path $tmp "$name.$suffix"
    $glsl = Join-Path $out "$name.$suffix.glsl"
    Remove-Item -ErrorAction SilentlyContinue $spv, $staged

    & slangc $src -target spirv -entry $entry -stage $stage -fvk-use-entrypoint-name -o $spv
    if ($LASTEXITCODE -ne 0) { throw "slangc failed for $name/$entry" }

    & naga $spv $staged --profile es300 --entry-point $entry
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $staged)) { throw "naga produced no output for $name/$entry" }

    # LF endings so the files match on every OS; the marker goes after #version.
    $src_text = (Get-Content -Raw $staged) -replace "`r`n", "`n"
    $src_text = $src_text -replace '(View_std140_block_\d+)(Vertex|Fragment)', '$1'
    $src_text = $src_text -replace '(_group_\d+_binding_\d+)_(vs|fs)\b', '$1'
    $lines = $src_text -split "`n", 2
    $text = $lines[0] + "`n// GENERATED by tools/build-shaders.ps1 from shaders/$name.slang. Do not edit.`n" + $lines[1]
    [System.IO.File]::WriteAllText($glsl, $text)
    Write-Host "built $glsl"
}
